class TestManifestContractError:
    """Test manifest contract violation when rendered manifest exists but has no Deployments."""

    def test_manifest_exists_but_no_deployments_is_contract_error(self) -> None:
        """Manifest exists but yields no Deployments must produce contract error, not silent fallback."""
        from scripts.k9b_cnpg_live_lab_monitor import get_expected_deployments_from_manifest

        # Manifest with no Deployment objects (only Namespace and ConfigMap)
        empty_manifest = """
apiVersion: v1
kind: Namespace
metadata:
  name: k9b-live-lab
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: k9b-config
  namespace: k9b-live-lab
"""
        with tempfile.TemporaryDirectory() as tmpdir:
            artifact_dir = Path(tmpdir)
            helm_dir = artifact_dir / "helm"
            helm_dir.mkdir(parents=True)
            rendered_path = helm_dir / "rendered-manifest.yaml"
            rendered_path.write_text(empty_manifest)

            # Manifest exists but has no Deployments
            assert rendered_path.exists()

            expected_deployments = get_expected_deployments_from_manifest(artifact_dir, "k9b", "k9b-live-lab")
            assert expected_deployments == [], "No Deployments should return empty list"

            # The CLI logic: manifest exists + no deployments = manifest contract error
            # This should NOT silently fall back to legacy mode with stale "Deployment k9b"
            if rendered_path.exists() and not expected_deployments:
                # This is the contract violation path - must NOT fall back
                assert True, "Manifest contract error path is correctly enforced"
                # Simulate the error result that CLI would produce
                result = {
                    "success": False,
                    "failure_class": "manifest_contract_error",
                    "expected_deployments": [],
                }
                assert result["failure_class"] == "manifest_contract_error"
                assert result["expected_deployments"] == []



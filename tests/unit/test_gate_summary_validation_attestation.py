def _write_attestation(
    *,
    attestation_path: Path,
    validated_path: str,
    validated_sha256: str,
    parser_identity: str = "scripts/factory/parse_gate_summary.py",
    decode_status: str = "pass",
    acceptance_status: str = "pass",
) -> None:
    payload = {
        "schema_version": 1,
        "validated_path": validated_path,
        "validated_sha256": validated_sha256,
        "validated_at": "2026-07-30T00:00:00+00:00",
        "parser_identity": parser_identity,
        "parser_command": "<test>",
        "parser_exit_code": 0,
        "parser_duration_ms": 0,
        "decode_status": decode_status,
        "acceptance_status": acceptance_status,
        "diagnostics": {},
    }
    attestation_path.write_text(
        json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8"
    )


def _build_repo_with_factory_artifact(tmp_path: Path) -> tuple[Path, Path, str]:
    factory = tmp_path / ".factory"
    factory.mkdir()
    artifact = factory / "gate-summary.json"
    artifact.write_text("{\"schema_version\": 1}", encoding="utf-8")
    sha = hashlib.sha256(artifact.read_bytes()).hexdigest()
    return artifact, tmp_path, sha


def test_verify_validation_attestation_accepts_portable_relative_path(tmp_path: Path) -> None:
    """The canonical committed attestation MUST verify end-to-end with
    no SHA mismatch and no path rejection."""
    artifact, repo_root, sha = _build_repo_with_factory_artifact(tmp_path)
    attestation_path = artifact.parent / "gate-summary-validation.json"
    _write_attestation(
        attestation_path=attestation_path,
        validated_path=".factory/gate-summary.json",
        validated_sha256=sha,
    )
    result = verify_validation_attestation(
        repo_root=repo_root, attestation_path=attestation_path
    )
    assert result.sha_matches is True
    assert result.decode_status == "pass"
    assert result.acceptance_status == "pass"
    assert result.parser_identity == "scripts/factory/parse_gate_summary.py"
    assert result.portable_validated_path == ".factory/gate-summary.json"
    assert result.validated_path == artifact.resolve()


def test_verify_validation_attestation_rejects_sha_mismatch(tmp_path: Path) -> None:
    """A mutation of the validated artifact between attestation write
    and verifier invocation MUST surface as a SHA mismatch."""
    artifact, repo_root, sha = _build_repo_with_factory_artifact(tmp_path)
    attestation_path = artifact.parent / "gate-summary-validation.json"
    # Mutate the artifact AFTER writing the attestation so the SHA
    # recorded in the attestation no longer matches the on-disk bytes.
    artifact.write_text("{\"mutated\": true}", encoding="utf-8")
    _write_attestation(
        attestation_path=attestation_path,
        validated_path=".factory/gate-summary.json",
        validated_sha256=sha,
    )
    with pytest.raises(_AttestationError) as exc:
        verify_validation_attestation(
            repo_root=repo_root, attestation_path=attestation_path
        )
    assert "SHA mismatch" in str(exc.value)



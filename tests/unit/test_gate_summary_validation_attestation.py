"""Runtime verifier tests for the portable validation attestation.

ACT-K9B-HULK-PROMOTION-FINAL-LOCAL-ACCEPTANCE01-CORRECTION05:

The verifier (:mod:`scripts.factory.gate_summary_validation_attestation`)
MUST accept portable repository-relative ``validated_path`` values
and reject absolute / traversal / outside-repo paths. The committed
attestation file is regenerated by the canonical producer, so its
contents MUST be identical on every runner (macOS developer
workstation, Linux CI runner).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

from scripts.factory.gate_summary_validation_attestation import (  # noqa: E402
    _AttestationError,
    _reject_forbidden_absolute,
    resolve_validated_path,
    verify_validation_attestation,
)

# ---------------------------------------------------------------------------
# Bounded path-prefix rejection
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "prefix",
    ["/Users/", "/home/runner/", "/home/circleci/", "/root/", "C:\\", "D:\\", "/private/"],
)
def test_forbidden_absolute_prefixes_are_rejected(prefix: str) -> None:
    with pytest.raises(_AttestationError) as exc:
        _reject_forbidden_absolute(prefix + "some/where")
    assert "forbidden absolute prefix" in str(exc.value) or "absolute path" in str(exc.value)


def test_bare_posix_absolute_path_is_rejected() -> None:
    """A bare absolute path not matching the explicit prefix list is
    also rejected -- the contract is "repository-relative only"."""
    with pytest.raises(_AttestationError) as exc:
        _reject_forbidden_absolute("/etc/passwd")
    assert "absolute path" in str(exc.value)


def test_empty_or_invalid_path_is_rejected() -> None:
    for bad in ("", None, 123):
        with pytest.raises(_AttestationError):
            _reject_forbidden_absolute(bad)  # type: ignore[arg-type]


